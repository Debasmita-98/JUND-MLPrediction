def supports_sample_weight(estimator):
    try:
        return "sample_weight" in inspect.signature(estimator.fit).parameters
    except (ValueError, TypeError):
        return False

results, trained, probas = [], {}, {}

def evaluate(name, clf):
    print(f"\n=== {name} ===")
    if supports_sample_weight(clf):
        clf.fit(X_train_use, y_train_small, sample_weight=sample_weight)
    else:
        clf.fit(X_train_use, y_train_small)

    y_pred = clf.predict(X_test_use)
    acc = accuracy_score(y_test, y_pred)
    prec, rec, f1, _ = precision_recall_fscore_support(
        y_test, y_pred, average="macro", zero_division=0
    )
    print(f"Acc: {acc:.4f} | Prec(macro): {prec:.4f} | Rec(macro): {rec:.4f} | F1(macro): {f1:.4f}")

    if SHOW_PLOTS:
        cm = confusion_matrix(y_test, y_pred, labels=np.unique(y_test))
        ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=np.unique(y_test)).plot(xticks_rotation=45)
        plt.title(f"Confusion Matrix — {name}")
        plt.tight_layout(); plt.show()

    auc = None
    if hasattr(clf, "predict_proba"):
        try:
            y_proba = clf.predict_proba(X_test_use)[:, 1]
            auc = roc_auc_score(y_test, y_proba)
            probas[name] = y_proba
            print(f"ROC-AUC: {auc:.4f}")
        except Exception:
            pass

    results.append({
        "model": name, "accuracy": acc, "precision_macro": prec,
        "recall_macro": rec, "f1_macro": f1, "roc_auc": auc
    })
    trained[name] = clf


